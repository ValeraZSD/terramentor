/**
 * Learning-feed composition — the home page's algorithm.
 *
 * The feed replaces the Today dashboard: instead of listing obligations, it
 * serves an ordered stream of things to DO — lesson cards teaching the
 * currently-scheduled leaves, inline questions that write mastery evidence,
 * SRS flashcard reviews, "recall" questions from decaying topics, and a
 * checkpoint card per topic that routes completion through the existing
 * mastery gate. Being behind schedule is handled here, by ordering (overdue
 * work first, "catch-up mode"), NOT by prompting the user to recalibrate.
 *
 * Design constraints:
 * - Deterministic given DB state + excludeKeys (the client sends the keys it
 *   already has; a re-fetch never reorders or re-serves what's on screen).
 *   The only sanctioned randomness is ghost-question sampling inside
 *   getGhostQuestions — recall cards are meant to vary between sessions.
 * - Works with AI OFF (the graceful-degradation rule in docs/ARCHITECTURE.md): teaching cards
 *   fall back to the node's own description/notes and saved quiz questions;
 *   flashcards/recall never needed AI at serve time to begin with.
 * - AI teaching content comes from the feed_items cache (pre-generated by
 *   server/feedGen.js) — composition never calls the model.
 */

// The feed's dials. Each has a default that was the constant it replaced, and
// each is now a setting (Settings → Learning → "Your feed") read at compose
// time: how many topics are taught at once, how many reviews and new cards a
// day may carry, how much of the tail is recall, and whether paper exercises,
// widgets and drills are generated at all. Clamped here so a hand-edited row
// cannot ask for a thousand new cards.
//
// Focus = how many nodes the feed teaches "at once". SRS honesty caps (the
// "696 due" fix): genuinely-due reviews per day, and never-reviewed cards
// introduced per project per day. NODE_QUESTIONS_PER_DAY is BKT hygiene: stop
// serving practice questions for a node once it has this many feed evidence
// rows today (generated sequences stay under it anyway; this guards the
// degraded saved-question path across repeat sessions).
export const FEED_DEFAULTS = Object.freeze({
    focusPerProject: 3,
    focusTotal: 6,
    dueReviewsPerDay: 60,
    newCardsPerProjectPerDay: 10,
    recallPerBatch: 4,
    maxParts: 5,
    practice: true,
    widgets: true,
});
const FEED_BOUNDS = {
    focusPerProject: [1, 10],
    focusTotal: [1, 20],
    dueReviewsPerDay: [0, 500],
    newCardsPerProjectPerDay: [0, 100],
    recallPerBatch: [0, 10],
    maxParts: [1, 5],
};
const FEED_SETTING_KEYS = {
    focusPerProject: 'feed_focus_per_project',
    focusTotal: 'feed_focus_total',
    dueReviewsPerDay: 'feed_due_per_day',
    newCardsPerProjectPerDay: 'feed_new_per_project',
    recallPerBatch: 'feed_recall_per_batch',
    maxParts: 'feed_max_parts',
    practice: 'feed_practice',
    widgets: 'feed_widgets',
};

/** The feed's dials as currently set, defaults filled in, numbers clamped. */
export function getFeedSettings() {
    const out = { ...FEED_DEFAULTS };
    let rows = [];
    try {
        rows = db.prepare(`SELECT key, value FROM settings WHERE key IN (${Object.values(FEED_SETTING_KEYS).map(() => '?').join(',')})`)
            .all(...Object.values(FEED_SETTING_KEYS));
    } catch { return out; }
    const byKey = new Map(rows.map(r => [r.key, r.value]));
    for (const [name, key] of Object.entries(FEED_SETTING_KEYS)) {
        if (!byKey.has(key)) continue;
        const raw = byKey.get(key);
        if (typeof FEED_DEFAULTS[name] === 'boolean') {
            out[name] = !(raw === 'false' || raw === '0' || raw === '');
        } else {
            const n = parseInt(raw, 10);
            if (Number.isFinite(n)) {
                const [lo, hi] = FEED_BOUNDS[name];
                out[name] = Math.max(lo, Math.min(hi, n));
            }
        }
    }
    return out;
}

const NODE_QUESTIONS_PER_DAY = 4;

const todayStr = () => new Date().toISOString().split('T')[0];

// Exported because feedGen.js reads the same JSON-in-a-TEXT-column rows and had
// its own byte-identical copy.
export function safeParse(text) {
    if (!text) return null;
    try { return JSON.parse(text); } catch { return null; }
}


/**
 * Write a repaired visual spec back into a cached feed item.
 *
 * Every surface that renders AI content has to own a write-back, or a
 * self-healing card is an LLM call on every page load (the lesson learned in
 * the assistant on 2026-09-04). The feed's cards are the awkward case, because
 * `feed_items.content` has two shapes: a lesson is raw markdown, while a
 * question or a practice card is a JSON payload whose text fields are
 * JSON-ESCAPED — so the spec as the renderer saw it does not appear in the
 * stored bytes at all, and a naive substring replace silently does nothing.
 *
 * Hence: parse when the content is an object or array, replace inside the
 * VALUES, re-serialise. `null` means the spec was not found — the caller says
 * so rather than writing an unchanged row.
 */
export function replaceSpecInContent(content, original, repaired) {
    const text = String(content ?? '');
    const trimmed = text.trimStart();
    // Only an object/array is treated as a payload. A lesson that happens to
    // start with a digit or a quote is markdown, and round-tripping it through
    // JSON would rewrite content nobody asked to change.
    if (trimmed.startsWith('{') || trimmed.startsWith('[')) {
        try {
            const next = JSON.stringify(replaceInStrings(JSON.parse(text), original, repaired));
            return next === JSON.stringify(JSON.parse(text)) ? null : next;
        } catch { /* not JSON after all — fall through to the plain path */ }
    }
    if (!text.includes(original)) return null;
    return text.split(original).join(repaired);
}

/** Replace `from` with `to` in every string inside a parsed JSON value. */
function replaceInStrings(value, from, to) {
    if (typeof value === 'string') return value.split(from).join(to);
    if (Array.isArray(value)) return value.map(v => replaceInStrings(v, from, to));
    if (value && typeof value === 'object') {
        return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, replaceInStrings(v, from, to)]));
    }
    return value;
}

/**
 * Normalize one AI-generated feed question. Sibling of finalizeQuiz's reducer
 * (studyMaterial.js): both dispatch the format-specific half to the answer
 * format registry, but — deliberately — this one accepts EVERY format, because
 * the feed grades open answers and code through the checker, whereas a saved
 * quiz admits a model-graded format only when the learner asked for it (the
 * Boss Fight must stay locally gradeable by default).
 * Returns the normalized question or null (drop — never guess a key).
 */
export function normalizeFeedQuestion(raw) {
    if (!raw || typeof raw !== 'object') return null;
    const q = {
        question: typeof raw.question === 'string' ? raw.question.trim() : '',
        type: raw.type,
    };
    if (!q.question) return null;
    // This reducer rebuilds the question key by key, so anything not named here
    // is dropped. A model never attaches media, but imported material does, and
    // a question whose photo silently disappeared is unanswerable rather than
    // merely plainer — so it is carried, validated.
    const media = sanitizeQuestionMedia(raw.media);
    if (media) q.media = media;
    // Options, key, explanation (and a code question's language and starter, a
    // sequence's items) — the fields the format owns, made honest, or null when
    // no honest key can be identified. Multiple choice shuffles in there, after
    // the explanation has been resolved against the model's own ordering.
    const shaped = normalizeQuestionFormat(raw);
    if (!shaped) return null;
    return Object.assign(q, shaped);
}

/**
 * The nodes the feed is teaching right now, most urgent first.
 * Per project (worst-pace project first): overdue open leaves oldest-first,
 * then today's scheduled leaves. Only when NOTHING is overdue or due today
 * anywhere does the feed "get ahead" with upcoming/unscheduled leaves.
 */
export function getFocusNodes({ maxPerProject, maxTotal } = {}) {
    const fs = getFeedSettings();
    maxPerProject = maxPerProject ?? fs.focusPerProject;
    maxTotal = maxTotal ?? fs.focusTotal;
    const today = todayStr();
    const projects = db.prepare(`
        SELECT p.id, p.name, p.color, p.icon, p.start_date, p.deadline,
               EXISTS(
                   SELECT 1 FROM flashcards f JOIN nodes n ON n.id = f.node_id
                   WHERE n.project_id = p.id
               ) AS has_cards
        FROM projects p
        WHERE COALESCE(p.status, 'active') = 'active'
        ORDER BY p.position ASC, p.created_at ASC
    `).all();

    const overdueStmt = db.prepare(`
        SELECT n.id, n.title, n.description, n.notes, n.scheduled_end, n.role
        FROM nodes n
        WHERE n.project_id = ? AND ${OPEN_LEAF} AND n.scheduled_end < ?
        ORDER BY n.scheduled_end ASC, n.id ASC
    `);
    const todayStmt = db.prepare(`
        SELECT n.id, n.title, n.description, n.notes, n.scheduled_end, n.role
        FROM nodes n
        WHERE n.project_id = ? AND ${OPEN_LEAF}
          AND n.scheduled_start <= ? AND n.scheduled_end >= ?
        ORDER BY n.position ASC, n.id ASC
    `);
    // Get-ahead: future-scheduled leaves first (soonest), then unscheduled in
    // creation order (the AI pipeline creates nodes in curriculum order).
    const aheadStmt = db.prepare(`
        SELECT n.id, n.title, n.description, n.notes, n.scheduled_end, n.role
        FROM nodes n
        WHERE n.project_id = ? AND ${OPEN_LEAF}
          AND (n.scheduled_start IS NULL OR n.scheduled_start > ?)
        ORDER BY CASE WHEN n.scheduled_start IS NULL THEN 1 ELSE 0 END,
                 n.scheduled_start ASC, n.id ASC
        LIMIT ?
    `);

    const infos = projects.map(p => {
        let pace = null;
        if (p.start_date && p.deadline) {
            try { pace = calculatePace(p.id); } catch { pace = null; }
        }
        return {
            project: p,
            pace,
            overdue: overdueStmt.all(p.id, today),
            todays: todayStmt.all(p.id, today, today),
        };
    });

    const urgency = (i) => i.overdue.length * 100 + (i.pace?.daysBehind || 0) * 10 + i.todays.length;
    infos.sort((a, b) => urgency(b) - urgency(a));

    const anyScheduledWork = infos.some(i => i.overdue.length || i.todays.length);
    // The Inbox is never scheduled — giving a capture a deadline would turn
    // "not read yet" into "overdue" by tomorrow. So instead it holds a standing
    // slot: its unscheduled leaves are always eligible, even on a day full of
    // real curriculum work. Urgency sorts it last (no overdue, nothing due), so
    // it fills the tail of the feed rather than displacing anything.
    // Read straight from settings rather than importing capture.js, which
    // already imports normalizeFeedQuestion from here — a cycle for one lookup.
    const inboxId = Number(
        db.prepare("SELECT value FROM settings WHERE key = 'inbox_project_id'").get()?.value
    ) || null;
    // A CARD COLLECTION gets the Inbox's standing slot, for the same reason. It
    // is never scheduled — thirty stages with deadlines would all be overdue by
    // next week, the exact "not read yet becomes overdue" failure the Inbox rule
    // exists to avoid — so without one it would be invisible in the feed on
    // every day that has any scheduled work, which for a real library is every
    // day.
    //
    // The test used to be `kind === 'deck'`, i.e. "did this arrive from Anki".
    // The property that actually earns the slot is the one stated above: it has
    // cards to serve and no dates it could ever be late against. Measured on the
    // real library (2026-09-09) the two sets are identical — all five imports
    // are unscheduled, and no scheduled project would qualify — so this changes
    // nothing today and stops being wrong the moment a course is given cards or
    // a deck is given a deadline.
    const isStanding = (info) =>
        info.project.id === inboxId
        || (!!info.project.has_cards && !(info.project.start_date && info.project.deadline));

    // ...and a standing slot has to be RESERVED, not merely last in line. Sorting
    // by urgency put the standing projects at the end (they have nothing overdue
    // by construction) and the loop stopped at `maxTotal` — so on the real
    // library, with 102 overdue leaves across five courses, the first project
    // filled all six slots and the deck contributed nothing at all. "Sorts last"
    // is not the same as "gets a turn". Scheduled work still gets first refusal
    // on the larger share; the reservation only guarantees the tail exists.
    //
    // This was latent for the Inbox too: a capture was equally unreachable on a
    // busy day, which is the opposite of what an inbox is for.
    const standingInfos = infos.filter(isStanding);
    const reserved = standingInfos.length
        ? Math.min(standingInfos.length, Math.max(1, Math.floor(maxTotal / 3)))
        : 0;

    const focus = [];
    const taken = new Set();
    // Whether this project's topics may be taught at all, asked once per project
    // rather than once per node (nodeRole.js: off by default for an import, so a
    // 5,000-card deck does not quietly start 32 lesson plans on the day it
    // arrives).
    const teaches = new Map();
    const projectTeachesCached = (id) => {
        if (!teaches.has(id)) teaches.set(id, projectTeaches(id));
        return teaches.get(id);
    };
    const take = (info, cap) => {
        const nodes = isStanding(info)
            ? aheadStmt.all(info.project.id, today, maxPerProject)
            : anyScheduledWork
                ? [...info.overdue, ...info.todays]
                : aheadStmt.all(info.project.id, today, maxPerProject);
        for (const n of nodes.slice(0, maxPerProject)) {
            if (focus.length >= cap) break;
            // The standing loop below calls this once per PASS, so a node the
            // previous pass already took must be skipped, not pushed again.
            if (taken.has(n.id)) continue;
            taken.add(n.id);
            focus.push({
                nodeId: n.id,
                title: n.title,
                description: n.description,
                notes: n.notes,
                scheduledEnd: n.scheduled_end,
                isOverdue: !!(n.scheduled_end && n.scheduled_end < today),
                projectId: info.project.id,
                projectName: info.project.name,
                projectColor: info.project.color,
                // Is there anything here to teach? Per NODE (a cut stage never
                // is) and per project (an import teaches nothing until asked).
                teachable: n.role !== 'pagination' && projectTeachesCached(info.project.id),
                pace: info.pace,
            });
        }
    };

    for (const info of infos) {
        if (isStanding(info)) continue;
        if (focus.length >= maxTotal - reserved) break;
        take(info, maxTotal - reserved);
    }
    // One node each, round-robin, so two decks and an inbox share the tail
    // instead of the first of them taking all of it.
    for (let pass = 0; pass < maxPerProject && focus.length < maxTotal; pass++) {
        for (const info of standingInfos) {
            if (focus.length >= maxTotal) break;
            take(info, Math.min(maxTotal, focus.length + 1));
        }
    }

    return {
        focus,
        projectInfos: infos,
        catchUpActive: infos.some(i => i.overdue.length > 0),
    };
}

/**
 * The focus set for ONE topic the learner opened on purpose ("Study this"),
 * or for a section, whose open leaves are taken in curriculum order.
 *
 * The same shape `getFocusNodes` returns, so composeFeed serves it through the
 * identical machinery — cached lessons, the degraded reading card, questions,
 * the paper exercise, the checkpoint — and nothing here decides what to teach:
 * the learner did. The schedule is deliberately ignored (a future or finished
 * topic can still be studied), which is the whole point of the entry.
 */
export function getFocusForNode(nodeId, { maxTotal } = {}) {
    maxTotal = maxTotal ?? getFeedSettings().focusTotal;
    const today = todayStr();
    const node = db.prepare(`
        SELECT n.id, n.project_id, n.is_note,
               p.id AS pid, p.name, p.color, p.icon, p.start_date, p.deadline
        FROM nodes n JOIN projects p ON p.id = n.project_id
        WHERE n.id = ?
    `).get(nodeId);
    if (!node || node.is_note) return { focus: [], projectInfos: [], catchUpActive: false };

    let pace = null;
    if (node.start_date && node.deadline) {
        try { pace = calculatePace(node.pid); } catch { pace = null; }
    }
    // The node itself when it is a leaf; otherwise its leaves, open first, in
    // curriculum order. Closed leaves come last so a finished section can
    // still be revisited without the study page reading as empty.
    // `path` is the walk order of the tree (position is per parent, so sorting
    // by it alone interleaves the leaves of sibling sub-topics).
    const leaves = db.prepare(`
        WITH RECURSIVE sub(id, path) AS (
            SELECT ?, ''
            UNION ALL
            SELECT n.id, sub.path || printf('%06d.', n.position) || printf('%09d/', n.id)
            FROM nodes n JOIN sub ON n.parent_id = sub.id WHERE n.is_note = 0
        )
        SELECT n.id, n.title, n.description, n.notes, n.scheduled_end, n.status, n.role
        FROM nodes n JOIN sub ON sub.id = n.id
        WHERE ${LEAF_NODE}
        ORDER BY CASE WHEN COALESCE(n.status, 'not_started') IN ('completed', 'skipped') THEN 1 ELSE 0 END,
                 sub.path ASC
        LIMIT ?
    `).all(nodeId, maxTotal);

    const focus = leaves.map(n => ({
        nodeId: n.id,
        title: n.title,
        description: n.description,
        notes: n.notes,
        scheduledEnd: n.scheduled_end,
        isOverdue: !!(n.scheduled_end && n.scheduled_end < today),
        projectId: node.pid,
        projectName: node.name,
        projectColor: node.color,
        // Same rule as the ambient feed: opening a topic on purpose does not
        // make a slice of card order into something a model can teach.
        teachable: n.role !== 'pagination' && projectTeaches(node.pid),
        pace,
    }));
    return { focus, projectInfos: [], catchUpActive: false };
}

/** Common card fields carried by every node-bound card. */
function cardBase(f) {
    return {
        nodeId: f.nodeId,
        projectId: f.projectId,
        projectName: f.projectName,
        projectColor: f.projectColor,
        nodeTitle: f.title,
    };
}

/**
 * Compose the next batch of feed cards.
 * excludeKeys: keys the client already holds — never re-served.
 * gate: getGateConfig() from index.js ({mode, threshold, bossPass, decayDays}).
 */
export function composeFeed({ limit = 15, excludeKeys = new Set(), gate, nodeId = null } = {}) {
    const today = todayStr();
    const excluded = (key) => excludeKeys.has(key);
    const fs = getFeedSettings();
    // A scoped feed ("Study this topic") teaches ONE node's leaves and serves
    // only their own flashcards — no recall from elsewhere, no other project's
    // reviews: the learner chose what to study, and the stream keeps to it.
    const scoped = Number.isInteger(nodeId) && nodeId > 0;
    const { focus, projectInfos } = scoped ? getFocusForNode(nodeId) : getFocusNodes();

    const readyStmt = db.prepare(`
        SELECT * FROM feed_items
        WHERE node_id = ? AND status = 'ready' AND kind IN ('lesson', 'question')
        ORDER BY seq ASC
    `);
    const planStmt = db.prepare(`SELECT * FROM feed_items WHERE node_id = ? AND kind = 'plan' LIMIT 1`);
    // Kept out of readyStmt on purpose: `planDone` below requires ready.length
    // === 0, and a practice row that sits unconsumed (the learner has no pen to
    // hand right now) would otherwise pin the node open and the checkpoint would
    // never appear.
    const practiceStmt = db.prepare(`
        SELECT * FROM feed_items WHERE node_id = ? AND kind = 'practice' AND status = 'ready' LIMIT 1
    `);
    const consumedLessonsStmt = db.prepare(`
        SELECT COUNT(*) AS c FROM feed_items WHERE node_id = ? AND kind = 'lesson' AND status = 'consumed'
    `);
    const latestQuizStmt = db.prepare(`
        SELECT id, questions FROM quizzes WHERE node_id = ? ORDER BY created_at DESC, id DESC LIMIT 1
    `);
    const nodeFeedEvidenceTodayStmt = db.prepare(`
        SELECT COUNT(*) AS c FROM mastery_evidence
        WHERE node_id = ? AND date(created_at) = ? AND metadata LIKE '%"source":"feed"%'
    `);
    const notesStmt = db.prepare(`
        SELECT title, description, notes FROM nodes WHERE parent_id = ? AND is_note = 1 ORDER BY position ASC
    `);

    let anyDegradedServed = false;
    let aiEnabled = false;
    try { aiEnabled = !!getAISettings().enabled; } catch { aiEnabled = false; }

    // --- Per-focus-node teaching queues -----------------------------------
    const nodeQueues = focus.map(f => {
        // A NODE WITH NOTHING TO TEACH IS NOT TAUGHT — a slice the importer cut
        // out of card order, or any topic in a project whose teaching is
        // switched off. It has no material — its content is the cards hanging
        // off it — so there is nothing here to write a lesson from, and every
        // path below would invent one: the AI path would ask a model to teach
        // "Stage 7", and the degraded path would serve the stage's own
        // description ("Cards 301–350 of the deck, in the order it
        // introduces them") as a reading card. Its contribution to the feed is
        // its FLASHCARDS, which are pooled separately below and pick their new
        // cards from exactly these focus nodes — so it is served in its own
        // order without any of this machinery.
        //
        // No checkpoint either: a checkpoint asks "have you proven this topic",
        // and a stage is proven by its cards maturing, which the scheduler
        // already tracks and the deck dashboard already draws.
        if (!f.teachable) return { f, cards: [], taughtOut: false, untaught: true };

        const plan = planStmt.get(f.nodeId);
        const ready = readyStmt.all(f.nodeId);
        const cards = [];
        let taughtOut = false;

        // Fully taught out = every planned lesson was generated AND consumed.
        const planParts = plan ? (safeParse(plan.content)?.parts?.length || 0) : 0;
        const planDone = plan && planParts > 0
            && ready.length === 0
            && consumedLessonsStmt.get(f.nodeId).c >= planParts;

        // A node whose generation started (plan row) but stalled with AI now
        // off would otherwise serve nothing forever — treat it as degraded.
        const stalledSequence = plan && ready.length === 0 && !planDone && !aiEnabled;

        if ((plan || ready.length) && !stalledSequence) {
            // AI path: serve cached generated cards in sequence order.
            for (const row of ready) {
                const key = `fi-${row.id}`;
                if (excluded(key)) continue;
                const meta = safeParse(row.meta) || {};
                if (row.kind === 'lesson') {
                    cards.push({
                        key, kind: 'lesson', feedItemId: row.id, ...cardBase(f),
                        partIndex: meta.partIndex ?? 1,
                        partCount: meta.partCount ?? 1,
                        partTitle: meta.partTitle || null,
                        markdown: row.content,
                        degraded: false,
                        source: 'generated',
                    });
                } else {
                    const q = safeParse(row.content);
                    if (q) {
                        cards.push({
                            key, kind: 'question', feedItemId: row.id, ...cardBase(f),
                            question: q,
                            source: 'generated',
                        });
                    }
                }
            }
            taughtOut = !!planDone;
        } else {
            // Degraded path (AI off, or content not generated yet): the node's
            // own material (description + the learner's `notes` column + child
            // note-nodes) + saved quiz questions, composed live, never stored.
            const noteChildren = notesStmt.all(f.nodeId);
            const sections = [];
            if (f.description?.trim()) sections.push(f.description.trim());
            if (f.notes?.trim()) sections.push(`### Your notes\n\n${f.notes.trim()}`);
            for (const note of noteChildren) {
                const body = [note.description, note.notes]
                    .map(s => s?.trim())
                    .filter(Boolean)
                    .join('\n\n');
                if (body) sections.push(`### ${note.title}\n\n${body}`);
            }
            let readingMd = sections.join('\n\n');
            const readKey = `read-${f.nodeId}`;
            if (readingMd && !excluded(readKey)) {
                cards.push({
                    key: readKey, kind: 'lesson', feedItemId: null, ...cardBase(f),
                    partIndex: 1, partCount: 1, partTitle: null,
                    markdown: readingMd,
                    degraded: true,
                    source: 'authored',
                });
                anyDegradedServed = true;
            }
            const quiz = latestQuizStmt.get(f.nodeId);
            if (quiz && nodeFeedEvidenceTodayStmt.get(f.nodeId, today).c < NODE_QUESTIONS_PER_DAY) {
                const qs = (safeParse(quiz.questions) || []).filter(q => q && !q.isGhost);
                qs.slice(0, 2).forEach((q, idx) => {
                    const key = `savedq-${quiz.id}-${idx}`;
                    if (excluded(key)) return;
                    cards.push({
                        key, kind: 'question', feedItemId: null, ...cardBase(f),
                        question: q,
                        source: 'saved',
                    });
                    anyDegradedServed = true;
                });
            }
            // Degraded taught-out: the node had servable material and this
            // session has been through all of it.
            taughtOut = cards.length === 0 && (!!readingMd || !!quiz);
        }

        // Paper practice goes LAST in the node's queue — work it by hand once the
        // topic has actually been taught, immediately before the checkpoint.
        // Served on both paths: the exercise and its worked solution are already
        // written, and self-marking needs no model, so an AI outage doesn't take
        // the paper loop down with it.
        //
        // `reference_solution` is deliberately NOT on the card. It is the answer
        // key, and shipping it with the exercise would put it one devtools panel
        // away from a learner who hasn't attempted the work yet. It is fetched
        // separately, only once they submit or explicitly ask to self-mark —
        // the same "teach on the way out, never during" rule as AnswerHelp.
        const practiceRow = fs.practice ? practiceStmt.get(f.nodeId) : null;
        if (practiceRow) {
            const key = `fi-${practiceRow.id}`;
            const exercise = safeParse(practiceRow.content);
            if (exercise && Array.isArray(exercise.rubric) && !excluded(key)) {
                cards.push({
                    key, kind: 'practice', feedItemId: practiceRow.id, ...cardBase(f),
                    mode: exercise.mode === 'photo' ? 'photo' : 'document',
                    brief: exercise.brief,
                    materials: exercise.materials || '',
                    rubric: exercise.rubric.map(r => ({ id: r.id, point: r.point, weight: r.weight })),
                });
            }
        }

        return { f, cards, taughtOut };
    });

    // --- Checkpoint builder -------------------------------------------------
    const checkpointCard = (f) => {
        const key = `checkpoint-${f.nodeId}`;
        if (excluded(key)) return null;
        const qRows = db.prepare(`
            SELECT result FROM feed_items WHERE node_id = ? AND kind = 'question' AND status = 'consumed'
        `).all(f.nodeId);
        let feedCorrect = 0, feedTotal = 0;
        for (const r of qRows) {
            const res = safeParse(r.result);
            if (res && typeof res.correct === 'boolean') {
                feedTotal++;
                if (res.correct) feedCorrect++;
            }
        }
        let masteryScore = 0;
        let eligible = false;
        let borrowedEstimate = false;
        try {
            const detail = getNodeMasteryDetail(f.nodeId);
            masteryScore = detail?.mastery_score || 0;
            const el = checkMasteryEligibility(f.nodeId, gate.threshold, gate.bossPass);
            eligible = !!el.eligible;
            // Part of the estimate was borrowed from a twin elsewhere, so the
            // BKT clause is suspended — the card has to say so, or a high
            // percentage sitting next to "not proven yet" reads as a bug.
            borrowedEstimate = !!el.borrowed_estimate;
        } catch { /* mastery tables always exist; belt and braces */ }
        const daysLeft = f.pace?.deadline ? daysUntil(f.pace.deadline) : null;
        return {
            key, kind: 'checkpoint', ...cardBase(f),
            feedCorrect, feedTotal, masteryScore, eligible, borrowedEstimate,
            gateMode: gate.mode,
            scheduledEnd: f.scheduledEnd,
            isOverdue: f.isOverdue,
            deadline: daysLeft != null ? { daysLeft, paceStatus: f.pace?.paceStatus || null } : null,
        };
    };

    // --- Flashcard pools ----------------------------------------------------
    // `stability IS NOT NULL` on every "today" counter below: a review done
    // in this app goes through FSRS and writes it, the Anki importer stamps
    // `last_reviewed` without it (see decks.js `introducedToday`). Without the
    // test an imported deck spent the day's review budget on cards the learner
    // last saw months ago in Anki, and the header announced thousands reviewed.
    const reviewsToday = db.prepare(`
        SELECT COUNT(*) AS c FROM flashcards f JOIN nodes n ON n.id = f.node_id
        ${ACTIVE_PROJECT_JOIN}
        WHERE date(f.last_reviewed) = ? AND f.stability IS NOT NULL
    `).get(today).c;
    const dueBudget = Math.max(0, fs.dueReviewsPerDay - reviewsToday);
    const focusIds = focus.map(f => f.nodeId);
    const inFocus = `f.node_id IN (${focusIds.map(() => '?').join(',')})`;
    // Scoped: only the studied topics' own cards, and never an empty IN ().
    const dueRows = dueBudget > 0 && (!scoped || focusIds.length) ? db.prepare(`
        SELECT f.*, n.title AS node_title, n.project_id,
               p.name AS project_name, p.color AS project_color
        FROM flashcards f JOIN nodes n ON n.id = f.node_id
        ${ACTIVE_PROJECT_JOIN}
        WHERE f.next_review IS NOT NULL AND f.next_review <= ${NOW_ISO}
        ${scoped ? `AND ${inFocus}` : ''}
        ORDER BY f.next_review ASC, f.difficulty DESC
        LIMIT ?
    `).all(...(scoped ? focusIds : []), dueBudget) : [];

    // How many cards this project has introduced today — one row per card,
    // read from the review log, exactly as the deck screen counts it
    // (`introducedToday` in decks.js, where the argument is written out). The
    // clause here used to be `review_count = 1`, which the (re)learning ladder
    // turned from an approximation into a systematic undercount: a new card
    // rated Good is answered twice before it graduates, so the cards learned
    // properly were the ones this stopped seeing, and the feed went on serving
    // new cards past the day's cap. `state_before = 0` is FSRS's New and
    // `source = 'app'` keeps an imported Anki revlog out of today's budget.
    const introducedByProject = new Map(db.prepare(`
        SELECT n.project_id AS pid, COUNT(DISTINCT r.card_id) AS c
        FROM review_log r
        JOIN flashcards f ON f.id = r.card_id
        JOIN nodes n ON n.id = f.node_id
        WHERE r.source = 'app' AND r.state_before = 0 AND date(r.reviewed_at) = ?
        GROUP BY n.project_id
    `).all(today).map(r => [r.pid, r.c]));

    // Every project's new-card rate comes from ONE function (decks.js
    // `getNewPerDay`), which is what keeps the home feed and the project's own
    // screen from rationing the same cards differently. It answers with the
    // project's own setting where there is one, and otherwise with a default
    // that depends on where the cards came from: Anki's 20 for an imported
    // collection, the feed's own dial (`feed_new_per_project`) for cards written
    // here. This used to branch on `kind` right here, so a project could be
    // rationed one way by the feed and another by its own screen.
    const newBudgetFor = new Map();
    for (const f of focus) {
        if (newBudgetFor.has(f.projectId)) continue;
        newBudgetFor.set(f.projectId, getNewPerDay(f.projectId));
    }
    const newRows = [];
    if (focusIds.length) {
        const candidates = db.prepare(`
            SELECT f.*, n.title AS node_title, n.project_id,
                   p.name AS project_name, p.color AS project_color
            FROM flashcards f JOIN nodes n ON n.id = f.node_id
            ${ACTIVE_PROJECT_JOIN}
            WHERE f.next_review IS NULL AND f.node_id IN (${focusIds.map(() => '?').join(',')})
            ORDER BY n.project_id ASC, f.id ASC
        `).all(...focusIds);
        const used = new Map();
        for (const row of candidates) {
            const count = used.get(row.project_id) ?? (introducedByProject.get(row.project_id) || 0);
            if (count >= (newBudgetFor.get(row.project_id) ?? fs.newCardsPerProjectPerDay)) continue;
            used.set(row.project_id, count + 1);
            newRows.push(row);
        }
    }

    const due = dueRows
        .map(r => ({ key: `fc-${r.id}`, kind: 'flashcard', card: r, isNew: false }))
        .filter(c => !excluded(c.key));
    const news = newRows
        .map(r => ({ key: `fcnew-${r.id}`, kind: 'flashcard', card: r, isNew: true }))
        .filter(c => !excluded(c.key));

    // --- Recall pool (the Remember loop, inline) ---------------------------
    const recallPool = [];
    for (const info of projectInfos) {
        if (recallPool.length >= fs.recallPerBatch) break;
        let ghosts = [];
        try { ghosts = getGhostQuestions(info.project.id, 2, gate.decayDays); } catch { ghosts = []; }
        for (const ghost of ghosts) {
            let daysSince = null;
            const nm = db.prepare(`SELECT last_updated FROM node_mastery WHERE node_id = ?`).get(ghost.nodeId);
            if (nm?.last_updated) {
                const ts = Date.parse(`${nm.last_updated.replace(' ', 'T')}Z`);
                if (Number.isFinite(ts)) daysSince = Math.max(0, Math.floor((Date.now() - ts) / 86400000));
            }
            ghost.questions.forEach((q, idx) => {
                if (recallPool.length >= fs.recallPerBatch) return;
                // `quizIndex` is the question's position in the quiz's own
                // array (stable across loads); the shuffled `idx` is not.
                const key = `recall-${ghost.nodeId}-${ghost.quizId}-${q.quizIndex ?? idx}`;
                if (excluded(key)) return;
                recallPool.push({
                    key, kind: 'recall',
                    nodeId: ghost.nodeId,
                    projectId: info.project.id,
                    projectName: info.project.name,
                    projectColor: info.project.color,
                    nodeTitle: ghost.title,
                    daysSince,
                    quizId: ghost.quizId,
                    question: q,
                });
            });
        }
    }

    // --- Interleave ---------------------------------------------------------
    const items = [];
    let queueIdx = 0;
    let sinceFlash = 0;
    let sinceRecall = 0;
    let flashInterval = 3;
    let flashSlot = 0;

    const pushFlash = () => {
        flashSlot++;
        const pick = (flashSlot % 3 === 0 && news.length) ? news.shift() : (due.shift() || news.shift());
        if (!pick) return false;
        items.push(pick);
        sinceFlash = 0;
        flashInterval = flashInterval === 3 ? 4 : 3;
        return true;
    };

    while (items.length < limit && queueIdx < nodeQueues.length) {
        const queue = nodeQueues[queueIdx];
        if (queue.cards.length === 0) {
            if (queue.taughtOut) {
                const cp = checkpointCard(queue.f);
                if (cp) items.push(cp);
            }
            queueIdx++;
            continue;
        }
        items.push(queue.cards.shift());
        sinceFlash++;
        sinceRecall++;
        if (sinceFlash >= flashInterval && (due.length || news.length)) pushFlash();
        if (sinceRecall >= 8 && recallPool.length) {
            items.push(recallPool.shift());
            sinceRecall = 0;
        }
    }

    // Teaching exhausted — fill the remainder with reviews and recall.
    while (items.length < limit && (due.length || news.length || recallPool.length)) {
        if (!pushFlash() && recallPool.length === 0) break;
        if (items.length < limit && recallPool.length) {
            items.push(recallPool.shift());
        }
    }

    // --- Notices ------------------------------------------------------------
    if (anyDegradedServed && !excluded('notice-ai')) {
        items.unshift({
            key: 'notice-ai', kind: 'notice',
            message: aiEnabled
                ? 'Personalized lessons are being prepared in the background — meanwhile the feed serves your own notes and saved questions.'
                : 'AI is off, so the feed is built from your notes, saved questions and reviews. Enable an AI model in Settings for generated lessons.',
        });
    }
    // All-clear notice only when there ARE projects (an empty items array with
    // zero active projects lets the client show its "create a project" state).
    // A scoped feed draws its own end state instead.
    if (!scoped && items.length === 0 && projectInfos.length > 0 && !excluded('notice-clear')) {
        items.push({
            key: 'notice-clear', kind: 'notice',
            message: "You're all caught up — nothing scheduled, no reviews due. Open a project to get ahead.",
        });
    }

    const exhausted = nodeQueues.every(q => q.cards.length === 0)
        && due.length === 0 && news.length === 0 && recallPool.length === 0;

    // Head starts for the topics on screen, keyed by node id rather than copied
    // onto every card: a four-part chapter would otherwise carry the same
    // payload five times, and the chapter — not the card — is what displays it.
    const transfers = getTransferInfoMap(items.map(i => i.nodeId).filter(Boolean));

    return { items, exhausted, transfers };
}

/** Slim header for the feed shell: today's activity, catch-up state, deadline chip. */
export function buildFeedHeader() {
    const today = todayStr();

    const lessonsDone = db.prepare(`
        SELECT COUNT(*) AS c FROM feed_items
        WHERE kind = 'lesson' AND status = 'consumed' AND date(consumed_at) = ?
    `).get(today).c;

    // Every feed answer (generated question, saved question, recall) writes
    // mastery_evidence tagged {"source":"feed"} — one query covers them all.
    const ev = db.prepare(`
        SELECT COALESCE(SUM(score), 0) AS s, COALESCE(SUM(total), 0) AS t, COUNT(*) AS c
        FROM mastery_evidence
        WHERE date(created_at) = ? AND metadata LIKE '%"source":"feed"%'
    `).get(today);

    // Same `stability IS NOT NULL` discriminator as composeFeed: reviews done
    // here, never the importer's stamp.
    const cardsReviewed = db.prepare(`
        SELECT COUNT(*) AS c FROM flashcards f JOIN nodes n ON n.id = f.node_id
        ${ACTIVE_PROJECT_JOIN}
        WHERE date(f.last_reviewed) = ? AND f.stability IS NOT NULL
    `).get(today).c;

    const newIntroduced = db.prepare(`
        SELECT COUNT(*) AS c FROM flashcards f JOIN nodes n ON n.id = f.node_id
        ${ACTIVE_PROJECT_JOIN}
        WHERE f.review_count = 1 AND date(f.last_reviewed) = ? AND f.stability IS NOT NULL
    `).get(today).c;

    const overdueRows = db.prepare(`
        SELECT n.project_id AS pid, p.name AS name, COUNT(*) AS c
        FROM nodes n
        ${ACTIVE_PROJECT_JOIN}
        WHERE ${OPEN_WORK_LEAF} AND n.scheduled_end < ?
        GROUP BY n.project_id
    `).all(today);
    const catchUp = {
        active: overdueRows.length > 0,
        overdueLeaves: overdueRows.reduce((a, r) => a + r.c, 0),
        projects: overdueRows.map(r => ({ projectId: r.pid, name: r.name, overdue: r.c })),
    };

    // Deadline chip: the most-pressed scheduled project (worst pace status,
    // then most days behind, then soonest deadline).
    const scheduled = db.prepare(`
        SELECT id, name, color, deadline FROM projects
        WHERE COALESCE(status, 'active') = 'active'
          AND start_date IS NOT NULL AND deadline IS NOT NULL AND deadline >= ?
    `).all(today);
    const RANK = { critical: 3, falling_behind: 2, on_track: 1 };
    let deadline = null;
    for (const p of scheduled) {
        let pace = null;
        try { pace = calculatePace(p.id); } catch { continue; }
        if (!pace?.hasSchedule) continue;
        const candidate = {
            projectId: p.id, name: p.name, color: p.color,
            deadline: p.deadline,
            daysLeft: daysUntil(p.deadline),
            paceStatus: pace.paceStatus || 'on_track',
            daysBehind: pace.daysBehind || 0,
        };
        if (!deadline
            || (RANK[candidate.paceStatus] || 0) > (RANK[deadline.paceStatus] || 0)
            || ((RANK[candidate.paceStatus] || 0) === (RANK[deadline.paceStatus] || 0)
                && (candidate.daysBehind > deadline.daysBehind
                    || (candidate.daysBehind === deadline.daysBehind && candidate.daysLeft < deadline.daysLeft)))) {
            deadline = candidate;
        }
    }

    return {
        date: today,
        stats: {
            itemsDoneToday: lessonsDone + ev.c + cardsReviewed,
            lessonsReadToday: lessonsDone,
            questionsAnsweredToday: ev.c,
            accuracyToday: ev.t > 0 ? ev.s / ev.t : null,
            cardsReviewedToday: cardsReviewed,
            newCardsIntroducedToday: newIntroduced,
        },
        catchUp,
        deadline,
    };
}

/**
 * Record a card interaction. Lessons just mark their cache row consumed;
 * questions/recall additionally write mastery evidence (single-question BKT
 * update — order-exact, unlike batched quiz attempts). Flashcards and
 * checkpoints do NOT come through here: flashcards self-account via the
 * existing PUT /api/ai/flashcards/:id SRS path, checkpoints via PUT /api/nodes/:id.
 */
export function consumeFeedItem({ key, kind, feedItemId = null, nodeId = null, result = null }) {
    let row = null;
    if (feedItemId != null) {
        row = db.prepare(`SELECT node_id, meta FROM feed_items WHERE id = ?`).get(feedItemId) || null;
        // `NOW_ISO`, not `datetime('now')`: this is the only writer of
        // `consumed_at` and two readers sort on the raw column
        // (`server/index.js` recentMisses, `server/today.js` buildTodayActivity).
        // A column holding both shapes sorts 'T' (0x54) after ' ' (0x20), so
        // every ISO row would order after every legacy one regardless of when
        // it happened — see NOW_ISO in database.js for the bug this is.
        const changed = db.prepare(`
            UPDATE feed_items SET status = 'consumed', consumed_at = ${NOW_ISO}, result = ?
            WHERE id = ? AND status = 'ready'
        `).run(result ? JSON.stringify(result) : null, feedItemId).changes;
        // A row that was already consumed has already had its evidence
        // written. A replayed request (a retry, a stale tab) must not credit
        // or debit the same answer twice.
        if (changed === 0) return { ok: true, duplicate: true };
    }
    if ((kind === 'question' || kind === 'recall') && (nodeId != null || row)) {
        const metadata = { source: 'feed', key: key || null };
        if (kind === 'recall') metadata.ghost = true;
        if (result?.gradedBy) metadata.gradedBy = result.gradedBy;
        // The item's format sets its guess floor, so BKT can discount a correct
        // true/false against a correct calculation. Read from the stored row
        // rather than trusted from the client — this decides mastery. The node
        // comes from the row for the same reason.
        if (row) {
            try {
                const qType = JSON.parse(row.meta || '{}').questionType;
                if (qType) metadata.questionType = qType;
            } catch { /* meta is advisory; a missing type just uses the default */ }
        }
        const correct = !!(result && result.correct);
        // An open answer the grader never judged (checkAnswerWithAI's fallback
        // says "trust yourself") is not evidence of a wrong answer. A correct
        // fallback verdict is an exact string match and is fine to credit.
        if (result?.gradedBy === 'fallback' && !correct) return { ok: true, ungraded: true };
        updateMasteryFromAttempt(row?.node_id ?? nodeId, correct ? 1 : 0, 1, 'quiz', metadata);
    }
    return { ok: true };
}
