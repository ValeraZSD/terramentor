// The evidence chart in docs/WHY_IT_WORKS.md and the README, and the table of
// sources beside it, drawn from ONE data file: docs/evidence/effect-sizes.json.
//
// Every bar carries its source in that file (citation, DOI or stable link, the
// sentence the number was read from, the day it was checked). The SVGs and the
// markdown table are build artefacts of it, so a number corrected in the data is
// corrected everywhere at once, and `tools/evidence-chart-gates.mjs` fails when
// a drawing or the table no longer matches the data.
//
// Two layouts, because one picture cannot serve both screens: GitHub shows a
// README image at its own width up to the column (838px on a PC) and shrinks
// it to fit a phone (294 to 364px). A chart wide enough for the PC would be
// shown at a third of its size on a phone, and a phone-sized one fills half
// the PC's column. So:
//
//   wide    one line per study (label, bar, value, source), for the PC;
//   narrow  the label and value, the source under it, then the bar, for a phone.
//
// The README picks one with `<picture>`, and GitHub constrains how. Its page
// script (the `themed-picture` element) REWRITES the media query of every
// `<source>` that names `prefers-color-scheme` when the reader has chosen a
// fixed theme, to "always" or "never" by the theme alone, so a source keyed on
// width AND theme loses its width. The wide source is therefore keyed on width
// only and colours itself: an SVG shown through `<img>` evaluates
// `prefers-color-scheme` against the page's `color-scheme`, which GitHub sets
// from the reader's theme (Chromium and Firefox, measured 2026-11-01). WebKit
// evaluates it against the OS instead, so on a light OS it draws the light
// colours on GitHub's dark page; the wide chart's light colours are therefore
// painted on a white card, readable on any page. The narrow charts keep one
// file per theme behind GitHub's own theme switch, and have a transparent
// background, since GitHub's light, dark and dimmed pages are three greys.
//
//   node tools/evidence-chart.mjs           write the SVGs and the table
//   node tools/evidence-chart.mjs --check   exit 1 if anything on disk is stale
import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DATA_PATH = join(repoRoot, 'docs', 'evidence', 'effect-sizes.json');
export const DOC_PATH = join(repoRoot, 'docs', 'WHY_IT_WORKS.md');
export const svgPath = (file) => join(repoRoot, 'docs', 'evidence', file);

export const TABLE_START = '<!-- evidence-table:start (generated by tools/evidence-chart.mjs; edit docs/evidence/effect-sizes.json) -->';
export const TABLE_END = '<!-- evidence-table:end -->';

// Ink and marks per theme: blue for a gain, red for a loss, which is the one bar
// whose sign is the point. The contrast each pair must reach on GitHub's pages,
// and the interval line on each bar, is asserted in evidence-chart-gates.mjs.
// The grid is deliberately faint and is not held to it.
export const THEMES = {
    light: {
        ink: '#1f2328', quiet: '#59636e', grid: '#e1e4e8', zero: '#8c959f',
        gain: '#2a78d6', loss: '#d1383d', ci: '#1f2328',
    },
    dark: {
        ink: '#f0f6fc', quiet: '#9198a1', grid: '#30363d', zero: '#6e7681',
        gain: '#3987e5', loss: '#e06060', ci: '#f0f6fc',
    },
};
/** GitHub's light page, painted behind the wide chart's light colours (see the header). */
export const LIGHT_CARD = '#ffffff';

/**
 * The README column is 838px from a 1280px window up; below 1280 GitHub's
 * sidebar takes 442px, so 1160 is where the column reaches 718px and the wide
 * chart's 15px labels are still shown at 13px. Narrower windows get the narrow
 * chart at its own size, or shrunk to a phone's column.
 */
export const WIDE_MEDIA = '(min-width: 1160px)';

/** Each drawing: its layout, and `auto` for colours chosen inside the SVG. */
export const CHARTS = [
    { file: 'effect-sizes-wide.svg', layout: 'wide', theme: 'auto' },
    { file: 'effect-sizes-light.svg', layout: 'narrow', theme: 'light' },
    { file: 'effect-sizes-dark.svg', layout: 'narrow', theme: 'dark' },
];

// Sizes in px at the image's own width. The narrow chart is 350px so a 390px
// phone's 324px column shows it at 93% (labels 15px); at 360px it is 84%.
export const LAYOUTS = {
    wide: { W: 840, size: { title: 20, sub: 14, head: 14, label: 15, small: 13, value: 15, axis: 13 } },
    narrow: { W: 350, size: { title: 19, sub: 14, head: 14, label: 16, small: 14, value: 16, axis: 13.5 } },
};
const FONT = 'system-ui, -apple-system, &quot;Segoe UI&quot;, Roboto, sans-serif';
const BAR = 12;          // bar thickness: thin, so the interval line over it stays visible
const GAP = 8;           // the least room between two texts, also asserted by the gate

/**
 * A width for system sans from character classes: there are no font metrics at
 * build time, and the viewer's font is not ours to choose (Segoe UI on Windows,
 * SF on a Mac, often the wider DejaVu Sans on Linux). Text is therefore laid out
 * and checked at `WIDER_FONT` times this estimate.
 */
export const WIDER_FONT = 1.15;
export const textWidth = (s, px, bold = false) => {
    let em = 0;
    for (const ch of s) {
        if (/[il.,:;'|!]/.test(ch)) em += 0.28;
        else if (/[mwMW]/.test(ch)) em += 0.86;
        else if (/[A-Z]/.test(ch)) em += 0.66;
        else if (/[0-9−-]/.test(ch)) em += 0.56;
        else if (ch === ' ') em += 0.28;
        else em += 0.53;
    }
    return em * px * (bold ? 1.06 : 1);
};
const laidOut = (s, px, bold = false) => textWidth(s, px, bold) * WIDER_FONT;

/** Words into lines no wider than `width` at `WIDER_FONT`. */
const wrap = (s, px, width) => {
    const lines = [];
    let cur = '';
    for (const word of s.split(' ')) {
        const next = cur ? `${cur} ${word}` : word;
        if (cur && laidOut(next, px) > width) { lines.push(cur); cur = word; } else cur = next;
    }
    if (cur) lines.push(cur);
    return lines;
};

const esc = (s) => String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Sign with a real minus, two decimals: the way the papers print it. Never "−0.00". */
export const fmt = (v) => {
    const digits = Math.abs(v).toFixed(2);
    return `${v < 0 && Number(digits) !== 0 ? '−' : ''}${digits}`;
};

/**
 * The source as the chart prints it. A working paper or preprint carries an
 * asterisk, which a line of `note` explains: a single unreviewed trial and a
 * peer-reviewed meta-analysis otherwise look the same on one axis.
 */
export const shortLabel = (r) => `${r.short}${r.reviewed === false ? '*' : ''}`;

/** A tick label: "0", "0.4", "−0.4". */
const tickLabel = (t) => (t === 0 ? '0' : fmt(t).replace(/0$/, ''));

/**
 * The chart in one layout, with colours as class names (filled in per theme by
 * `renderSvg`), and where each piece of text and each mark sits: what the gate
 * checks. Text boxes are at `WIDER_FONT`.
 */
export function layout(data, name) {
    const { W, size: S } = LAYOUTS[name];
    const wide = name === 'wide';
    const rows = data.groups.flatMap((g) => g.rows);
    const parts = [];
    const lines = [];   // grid and zero lines, drawn under everything else
    const marks = [];   // bars and intervals
    const texts = [];   // { s, left, right, top, bottom }
    const markBoxes = [];

    const text = (tx, ty, runs, { size, anchor = 'start' }) => {
        // `runs`: a string, or [{ s, cls, bold }] set one after another on one line.
        const list = typeof runs === 'string' ? [{ s: runs }] : runs;
        const w = list.reduce((sum, r) => sum + laidOut(r.s, size, r.bold), 0);
        const left = anchor === 'start' ? tx : anchor === 'end' ? tx - w : tx - w / 2;
        const s = list.map((r) => r.s).join('');
        texts.push({ s, left, right: left + w, top: ty - size * 0.8, bottom: ty + size * 0.25 });
        const span = (r) => `${r.bold ? ' font-weight="600"' : ''} class="${r.cls || 'ink'}"`;
        const head = `<text x="${tx.toFixed(1)}" y="${ty.toFixed(1)}" font-size="${size}"${anchor !== 'start' ? ` text-anchor="${anchor}"` : ''}`;
        parts.push(list.length === 1
            ? `${head}${span(list[0])}>${esc(list[0].s)}</text>`
            : `${head}>${list.map((r) => `<tspan${span(r)}>${esc(r.s)}</tspan>`).join('')}</text>`);
    };

    // Columns. Wide: label | plot | value | source, each as wide as its longest
    // text, words left-aligned and numbers right-aligned. Narrow: the plot spans
    // the image, the text sits on the lines above it. The gaps can be small:
    // the widths are already 15% over the estimate.
    const labelW = Math.max(...rows.map((r) => laidOut(r.label, S.label)));
    const valueW = Math.max(...rows.map((r) => laidOut(fmt(r.value), S.value, true)));
    const sourceW = Math.max(...rows.map((r) => laidOut(shortLabel(r), S.small)));
    const sourceLeft = Math.floor(W - sourceW);
    const plotLeft = wide ? Math.ceil(labelW + 16) : 0;
    const valueRight = wide ? sourceLeft - 20 : W;
    const plotRight = wide ? Math.floor(valueRight - valueW - 20) : W;
    const { min, max } = data.axis;
    const x = (v) => plotLeft + ((v - min) / (max - min)) * (plotRight - plotLeft);
    const x0 = x(0);

    // Ticks: every one in the data that has room for its label, keeping 0;
    // if two labels would meet, every second, and so on.
    const all = data.axis.ticks;
    const zeroAt = all.indexOf(0);
    let ticks = all;
    for (let step = 1; step <= all.length; step++) {
        ticks = all.filter((_, i) => (i - zeroAt) % step === 0);
        const boxes = ticks.map((t) => {
            const w = laidOut(tickLabel(t), S.axis);
            const left = x(t) - w / 2;
            return [Math.max(left, plotLeft), Math.max(left, plotLeft) + w];
        });
        if (boxes.every((b, i) => i === 0 || b[0] >= boxes[i - 1][1] + GAP)) break;
    }

    let y = 0;
    for (const line of wrap(data.title.join(' '), S.title, W)) { y += S.title + 5; text(0, y, [{ s: line, bold: true }], { size: S.title }); }
    y += 4;
    for (const para of data.subtitle) {
        for (const line of wrap(para, S.sub, W)) { y += S.sub + 6; text(0, y, [{ s: line, cls: 'quiet' }], { size: S.sub }); }
    }
    y += wide ? 18 : 16;

    let plotTop = 0;
    for (const [gi, group] of data.groups.entries()) {
        // "Techniques the loop uses · meta-analyses": the name in ink, what it
        // holds in the quiet colour, on a second line when both do not fit.
        const [name1, ...rest] = group.label.split(' · ');
        const tail = rest.length ? ` · ${rest.join(' · ')}` : '';
        y += S.head + (gi === 0 ? 4 : wide ? 16 : 20);
        if (laidOut(name1, S.head, true) + laidOut(tail, S.head) <= W) {
            text(0, y, [{ s: name1, bold: true }, { s: tail, cls: 'quiet' }], { size: S.head });
        } else {
            text(0, y, [{ s: name1, bold: true }], { size: S.head });
            y += S.head + 5;
            text(0, y, [{ s: tail.replace(/^ · /, ''), cls: 'quiet' }], { size: S.head });
        }
        y += wide ? 8 : 10;
        const groupTop = y;
        if (gi === 0) plotTop = y;
        for (const row of group.rows) {
            let barY;
            if (wide) {
                const ROW = 30;
                const base = y + ROW / 2 + S.label * 0.35;
                text(0, base, row.label, { size: S.label });
                text(valueRight, base, [{ s: fmt(row.value), bold: true }], { size: S.value, anchor: 'end' });
                text(sourceLeft, base, [{ s: shortLabel(row), cls: 'quiet' }], { size: S.small });
                barY = y + (ROW - BAR) / 2;
                y += ROW;
            } else {
                const base = y + S.label;
                text(0, base, row.label, { size: S.label });
                text(W, base, [{ s: fmt(row.value), bold: true }], { size: S.value, anchor: 'end' });
                const sourceBase = base + S.small + 4;
                text(0, sourceBase, [{ s: shortLabel(row), cls: 'quiet' }], { size: S.small });
                barY = sourceBase + 8;
                y = barY + BAR + 16;
                // The zero line runs only beside each bar here, since text
                // crosses the plot on the lines above it.
                lines.push(`<path d="M${x0.toFixed(1)},${(barY - 4).toFixed(1)}V${(barY + BAR + 4).toFixed(1)}" class="zero" stroke-width="1.5"/>`);
            }
            const xa = Math.min(x0, x(row.value));
            const xb = Math.max(x0, x(row.value));
            const cls = row.value < 0 ? 'loss' : 'gain';
            // Square at zero, 4px round at the data end: the bar reads as starting from zero.
            const r = Number(Math.min(4, (xb - xa) / 2).toFixed(1));
            const by = Number(barY.toFixed(1));
            const d = row.value >= 0
                ? `M${xa.toFixed(1)},${by}H${(xb - r).toFixed(1)}A${r},${r} 0 0 1 ${xb.toFixed(1)},${(by + r).toFixed(1)}V${(by + BAR - r).toFixed(1)}A${r},${r} 0 0 1 ${(xb - r).toFixed(1)},${(by + BAR).toFixed(1)}H${xa.toFixed(1)}Z`
                : `M${xb.toFixed(1)},${by}H${(xa + r).toFixed(1)}A${r},${r} 0 0 0 ${xa.toFixed(1)},${(by + r).toFixed(1)}V${(by + BAR - r).toFixed(1)}A${r},${r} 0 0 0 ${(xa + r).toFixed(1)},${(by + BAR).toFixed(1)}H${xb.toFixed(1)}Z`;
            marks.push(`<path d="${d}" class="${cls}"><title>${esc(`${row.label}: ${fmt(row.value)} (${shortLabel(row)})`)}</title></path>`);
            markBoxes.push({ id: row.id, left: xa, right: xb, top: by, bottom: by + BAR });
            if (Array.isArray(row.ci)) {
                const [lo, hi] = row.ci;
                const cy = (by + BAR / 2).toFixed(1);
                const [c1, c2] = [(by + BAR / 2 - 4).toFixed(1), (by + BAR / 2 + 4).toFixed(1)];
                marks.push(`<path data-row="${row.id}" d="M${x(lo).toFixed(1)},${cy}H${x(hi).toFixed(1)}M${x(lo).toFixed(1)},${c1}V${c2}M${x(hi).toFixed(1)},${c1}V${c2}" class="ci" stroke-width="1.5" fill="none"/>`);
                markBoxes.push({ id: row.id, left: x(lo), right: x(hi), top: by + BAR / 2 - 4, bottom: by + BAR / 2 + 4 });
            }
        }
        if (wide) {
            // Grid and zero line per group: the group's heading may run into the
            // plot's columns, and a line through a word reads as a strike.
            const inner = ticks.filter((t) => t !== 0).map((t) => `M${x(t).toFixed(1)},${groupTop.toFixed(1)}V${y.toFixed(1)}`).join('');
            if (inner) lines.push(`<path d="${inner}" class="grid" stroke-width="1"/>`);
            lines.push(`<path d="M${x0.toFixed(1)},${groupTop.toFixed(1)}V${y.toFixed(1)}" class="zero" stroke-width="1.5"/>`);
        }
    }
    const plotBottom = wide ? y : y - 10;

    // The axis: in the narrow chart a hairline with ticks, since its grid is
    // only the zero beside each bar.
    if (!wide) {
        const tickMarks = ticks.map((t) => `M${x(t).toFixed(1)},${plotBottom.toFixed(1)}v4`).join('');
        lines.push(`<path d="M${plotLeft},${plotBottom.toFixed(1)}H${plotRight}${tickMarks}" class="grid" stroke-width="1"/>`);
    }
    y = plotBottom + S.axis + (wide ? 8 : 10);
    for (const t of ticks) {
        const w = laidOut(tickLabel(t), S.axis);
        const anchor = x(t) - w / 2 < plotLeft ? 'start' : x(t) + w / 2 > plotRight ? 'end' : 'middle';
        const tx = anchor === 'start' ? Math.max(x(t), plotLeft) : anchor === 'end' ? Math.min(x(t), plotRight) : x(t);
        text(tx, y, [{ s: tickLabel(t), cls: 'quiet' }], { size: S.axis, anchor });
    }
    y += S.small + 8;
    text((plotLeft + plotRight) / 2, y, [{ s: data.axis.label, cls: 'quiet' }], { size: S.small, anchor: 'middle' });
    y += wide ? 14 : 16;
    for (const para of data.note) {
        for (const line of wrap(para, S.small, W)) { y += S.small + 6; text(0, y, [{ s: line, cls: 'quiet' }], { size: S.small }); }
    }
    const H = Math.ceil(y + 6);
    return { W, H, parts, lines, marks, texts, markBoxes, plot: { left: plotLeft, right: plotRight, top: plotTop, bottom: plotBottom } };
}

/** The colour rules for one theme, as CSS. */
const palette = (c) => [
    `.ink{fill:${c.ink}}.quiet{fill:${c.quiet}}.gain{fill:${c.gain}}.loss{fill:${c.loss}}`,
    `.grid{stroke:${c.grid};fill:none}.zero{stroke:${c.zero};fill:none}.ci{stroke:${c.ci}}`,
].join('');

/**
 * One drawing. `auto` carries both palettes and picks with the page's colour
 * scheme, its light one on a white card (see the header for why).
 */
export function renderSvg(data, chart) {
    const L = layout(data, chart.layout);
    const style = chart.theme === 'auto'
        ? `${palette(THEMES.light)}.card{fill:${LIGHT_CARD}}@media (prefers-color-scheme: dark){${palette(THEMES.dark)}.card{fill:none}}`
        : palette(THEMES[chart.theme]);
    const titleText = data.title.join(' ');
    return [
        `<svg xmlns="http://www.w3.org/2000/svg" width="${L.W}" height="${L.H}" viewBox="0 0 ${L.W} ${L.H}" role="img" aria-labelledby="t d" font-family="${FONT}">`,
        `<title id="t">${esc(titleText)}</title>`,
        `<desc id="d">${esc(data.groups.flatMap((g) => g.rows.map((r) => `${r.label}, ${shortLabel(r)}: ${fmt(r.value)}`)).join('; '))}</desc>`,
        `<style>${style}</style>`,
        ...(chart.theme === 'auto' ? [`<rect class="card" width="${L.W}" height="${L.H}"/>`] : []),
        ...L.lines,
        ...L.marks,
        ...L.parts,
        '</svg>',
        '',
    ].join('\n');
}

/**
 * A table cell: a `|` would split the cell and a `[` or `]` would break the
 * source link. A `\` is doubled too, so it shows as typed and cannot cancel the
 * escape in front of a `|` that follows it.
 */
const cell = (s) => String(s).replace(/([\\|[\]])/g, '\\$1');

/** A link target in a table cell: an unescaped `)` would end the link early and a `|` would split the cell. */
const cellUrl = (s) => String(s).replace(/([\\|()])/g, '\\$1');

/** The table of sources in the doc: one row per bar, in the chart's order. */
export function renderTable(data) {
    const lines = [
        TABLE_START,
        '',
        '| Result | Effect | 95% CI | Studies or people | Compared with | Note | Source |',
        '| --- | --- | --- | --- | --- | --- | --- |',
    ];
    for (const group of data.groups) {
        lines.push(`| **${cell(group.label)}** | | | | | | |`);
        for (const r of group.rows) {
            const ci = Array.isArray(r.ci) ? `${fmt(r.ci[0])} to ${fmt(r.ci[1])}` : 'not extracted';
            const effect = r.metric === 'SD' ? `${fmt(r.value)} SD` : `${r.metric} = ${fmt(r.value)}`;
            const link = `[${cell(r.source.cite)}](${cellUrl(r.source.url)})`;
            lines.push(`| ${[r.label, effect, ci, r.size, r.compared, r.note || '', link].map((v, i) => (i === 6 ? v : cell(v))).join(' | ')} |`);
        }
    }
    lines.push('', TABLE_END);
    return lines.join('\n');
}

export const loadData = () => JSON.parse(readFileSync(DATA_PATH, 'utf8'));

/** Compare as LF: a Windows checkout with autocrlf holds these files as CRLF. */
export const lf = (s) => s.replace(/\r\n/g, '\n');

/**
 * The doc with its table replaced by a fresh one, as LF. Throws unless each
 * marker is there exactly once, start before end: a second copy of the table
 * would otherwise stay in the doc, stale, while the first one passes.
 */
export function docWithTable(doc, data) {
    const text = lf(doc);
    const count = (m) => text.split(m).length - 1;
    const a = text.indexOf(TABLE_START);
    const b = text.indexOf(TABLE_END);
    if (count(TABLE_START) !== 1 || count(TABLE_END) !== 1 || b < a) {
        throw new Error(`${DOC_PATH} needs each evidence-table marker exactly once, start before end`);
    }
    return text.slice(0, a) + renderTable(data) + text.slice(b + TABLE_END.length);
}

/** Every generated file and what it should hold, as LF. */
export function expectedOutputs(data = loadData()) {
    return [
        ...CHARTS.map((c) => [svgPath(c.file), renderSvg(data, c)]),
        [DOC_PATH, docWithTable(readFileSync(DOC_PATH, 'utf8'), data)],
    ];
}

function main() {
    const check = process.argv.includes('--check');
    let stale = 0;
    for (const [path, content] of expectedOutputs()) {
        let current = null;
        try { current = readFileSync(path, 'utf8'); } catch { /* missing = stale */ }
        if (current !== null && lf(current) === content) continue;
        if (check) { stale++; console.log(`stale: ${path}`); continue; }
        // Keep the line endings the checkout already uses for the file.
        const crlf = current !== null && current.includes('\r\n');
        writeFileSync(path, crlf ? content.replace(/\n/g, '\r\n') : content);
        console.log(`wrote ${path}`);
    }
    if (check && stale) { console.log('Run: node tools/evidence-chart.mjs'); process.exit(1); }
    if (check) console.log('evidence chart and table are up to date');
}

// Compare real paths: run through a junction, a symlink or a subst drive, argv[1]
// is the path as typed while import.meta.url is already resolved, and a plain
// comparison would skip main() and let `--check` pass without checking.
const real = (p) => { try { return realpathSync.native(p); } catch { return p; } };
if (process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url))) main();
