// The evidence chart in docs/WHY_IT_WORKS.md and the README, and the table of
// sources beside it, drawn from ONE data file: docs/evidence/effect-sizes.json.
//
// Every bar carries its source in that file (citation, DOI or stable link, the
// sentence the number was read from, the day it was checked). The SVGs and the
// markdown table are build artefacts of it, so a number corrected in the data is
// corrected everywhere at once, and `tools/evidence-chart-gates.mjs` fails when
// a drawing or the table no longer matches the data.
//
// Three layouts, because one picture cannot serve every column: GitHub shows a
// README image at its own width up to the column and shrinks it to fit, and
// the column runs from 254px on a small phone to 1012px on a wide doc page. A
// chart wide enough for a PC would be shown at a third of its size on a phone,
// and a phone-sized one fills half a PC's column. So:
//
//   wide    one line per study (label, bar, value, source) on faint alternate
//           bands, for a full PC window;
//   medium  label, bar and value on a line, the source under the label, for a
//           half-screen window, a small laptop or a tablet;
//   narrow  the label, the source under it, then the bar with its value at the
//           end, for a phone. Its scale starts just below the lowest bar, so
//           the bars get the width; an interval that runs past it ends in an arrow.
//
// Which one a window gets follows from GitHub's column at that window width
// (`GITHUB_COLUMN`, measured): the widest layout whose labels are still shown
// at `LABEL_FLOOR` px and its smallest text at `TEXT_FLOOR` px. The generator
// writes those width queries into the README's and the doc's `<picture>`.
//
// GitHub constrains how a `<picture>` may choose. Its page script (the
// `themed-picture` element) REWRITES the media query of every `<source>` that
// names `prefers-color-scheme` when the reader has chosen a fixed theme, to
// "always" or "never" by the theme alone, so a source keyed on width AND theme
// loses its width. The wide and medium sources are therefore keyed on width
// only and colour themselves: an SVG shown through `<img>` evaluates
// `prefers-color-scheme` against the page's `color-scheme`, which GitHub sets
// from the reader's theme (Chromium and Firefox, measured 2026-11-01). WebKit
// evaluates it against the OS instead, so a reader whose GitHub theme differs
// from the OS gets the other palette: light colours on a dark page, or dark
// ones on a white page. Each palette is therefore painted on a card of the
// default page it was made for (white, and GitHub dark's #0d1117), readable on
// any page; on GitHub's dimmed theme the dark card shows as a darker box. The
// narrow charts keep one file per theme behind GitHub's own theme switch, and
// have a transparent background.
//
//   node tools/evidence-chart.mjs           write the SVGs, the table and the width queries
//   node tools/evidence-chart.mjs --check   exit 1 if anything on disk is stale
