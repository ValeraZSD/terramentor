// The evidence chart in docs/WHY_IT_WORKS.md and the README, and the table of
// sources beside it, drawn from ONE data file: docs/evidence/effect-sizes.json.
//
// Every bar carries its source in that file (citation, DOI or stable link, the
// sentence the number was read from, the day it was checked). The SVGs and the
// markdown table are build artefacts of it, so a number corrected in the data is
// corrected everywhere at once, and `tools/evidence-chart-gates.mjs` fails when
// a drawing or the table no longer matches the data.
//
// Two SVGs, because GitHub picks an image per theme through `<picture>` and
// `prefers-color-scheme`, and an SVG shown through `<img>` cannot read the
// page's theme itself. Both have a transparent background: GitHub's light,
// dark and dimmed pages are three different greys, and a painted card would
// sit on each as a box.
//
// The layout is one column, the label above its bar, because GitHub shrinks a
// README image to the phone's width: a 460px drawing on a 390px phone is shown
// at about three quarters size, and a label beside its bar would leave the bars
// no room. Text sizes are chosen so the smallest still reads at that scale.
//
//   node tools/evidence-chart.mjs           write the SVGs and the table
//   node tools/evidence-chart.mjs --check   exit 1 if anything on disk is stale
import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DATA_PATH = join(repoRoot, 'docs', 'evidence', 'effect-sizes.json');
export const DOC_PATH = join(repoRoot, 'docs', 'WHY_IT_WORKS.md');
export const svgPath = (theme) => join(repoRoot, 'docs', 'evidence', `effect-sizes-${theme}.svg`);

export const TABLE_START = '<!-- evidence-table:start (generated by tools/evidence-chart.mjs; edit docs/evidence/effect-sizes.json) -->';
export const TABLE_END = '<!-- evidence-table:end -->';

// Ink and marks per theme: blue for a gain, red for a loss, which is the one bar
// whose sign is the point. The contrast each pair must reach on GitHub's pages,
// and the interval line on each bar, is asserted in evidence-chart-gates.mjs.
// The grid is deliberately faint and is not held to it.
export const THEMES = {
    light: {
        ink: '#1f2328', quiet: '#59636e', grid: '#e1e4e8', zero: '#8c959f',
        gain: '#2a78d6', loss: '#d1383d', ci: '#1f2328',
    },
    dark: {
        ink: '#f0f6fc', quiet: '#9198a1', grid: '#30363d', zero: '#6e7681',
        gain: '#3987e5', loss: '#e06060', ci: '#f0f6fc',
    },
};

export const W = 460;
const FONT = 'system-ui, -apple-system, &quot;Segoe UI&quot;, Roboto, sans-serif';
export const SIZE = { title: 19, label: 17, small: 14, value: 16, axis: 13.5 };
const ROW = 52;          // one row: label line, then the bar
const BAR = 12;          // bar thickness: thin, so the interval line over it stays visible

/**
 * A width for system sans from character classes: there are no font metrics at
 * build time, and the viewer's font is not ours to choose (Segoe UI on Windows,
 * SF on a Mac, often the wider DejaVu Sans on Linux). Text is therefore laid out
 * and checked at `WIDER_FONT` times this estimate.
 */
export const WIDER_FONT = 1.15;
export const textWidth = (s, px, bold = false) => {
    let em = 0;
    for (const ch of s) {
        if (/[il.,:;'|!]/.test(ch)) em += 0.28;
        else if (/[mwMW]/.test(ch)) em += 0.86;
        else if (/[A-Z]/.test(ch)) em += 0.66;
        else if (/[0-9−-]/.test(ch)) em += 0.56;
        else if (ch === ' ') em += 0.28;
        else em += 0.53;
    }
    return em * px * (bold ? 1.06 : 1);
};

const esc = (s) => String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Sign with a real minus, two decimals: the way the papers print it. Never "−0.00". */
export const fmt = (v) => {
    const digits = Math.abs(v).toFixed(2);
    return `${v < 0 && Number(digits) !== 0 ? '−' : ''}${digits}`;
};

/**
 * The source as the chart prints it. A working paper or preprint carries an
 * asterisk, which a line of `note` explains: a single unreviewed trial and a
 * peer-reviewed meta-analysis otherwise look the same on one axis.
 */
export const shortLabel = (r) => `${r.short}${r.reviewed === false ? '*' : ''}`;

/** The chart for one theme, and where each piece of text sits (at `WIDER_FONT`). */
export function layout(data, theme) {
    const c = THEMES[theme];
    const { min, max, ticks } = data.axis;
    const x = (v) => ((v - min) / (max - min)) * W;
    const x0 = x(0);
    const parts = [];
    const texts = [];   // { s, left, right, top, bottom }: what the gate checks
    const boxes = [];   // the same, padded, so the vertical lines can stop short of it
    let y = 0;

    const text = (tx, ty, s, { size = SIZE.label, fill = c.ink, weight = 400, anchor = 'start' } = {}) => {
        const w = textWidth(s, size, weight !== 400) * WIDER_FONT;
        const left = anchor === 'start' ? tx : anchor === 'end' ? tx - w : tx - w / 2;
        const top = ty - size * 0.8;
        const bottom = ty + size * 0.25;
        texts.push({ s, left, right: left + w, top, bottom });
        boxes.push({ x1: left - 4, x2: left + w + 4, y1: top - 2, y2: bottom + 2 });
        parts.push(`<text x="${tx.toFixed(1)}" y="${ty.toFixed(1)}" font-size="${size}" fill="${fill}"` +
            `${weight !== 400 ? ` font-weight="${weight}"` : ''}${anchor !== 'start' ? ` text-anchor="${anchor}"` : ''}>${esc(s)}</text>`);
    };

    // Title and subtitle.
    for (const line of data.title) { y += SIZE.title + 5; text(0, y, line, { size: SIZE.title, weight: 600 }); }
    y += 6;
    for (const line of data.subtitle) { y += SIZE.small + 5; text(0, y, line, { size: SIZE.small, fill: c.quiet }); }
    y += 18;

    let plotTop = 0;
    const rowsSvg = [];
    for (const [i, group] of data.groups.entries()) {
        y += SIZE.small + (i === 0 ? 4 : 16);
        text(0, y, group.label, { size: SIZE.small, fill: c.quiet, weight: 600 });
        y += 12;
        if (i === 0) plotTop = y - 6;   // the lines start under the first heading
        for (const row of group.rows) {
            const top = y;
            text(0, top + SIZE.label, row.label);
            text(W, top + SIZE.label, shortLabel(row), { size: SIZE.small, fill: c.quiet, anchor: 'end' });
            const by = top + SIZE.label + 9;
            const xa = Math.min(x0, x(row.value));
            const xb = Math.max(x0, x(row.value));
            const fill = row.value < 0 ? c.loss : c.gain;
            // Square at zero, 4px round at the data end: the bar reads as starting from zero.
            const r = Number(Math.min(4, (xb - xa) / 2).toFixed(1));
            const d = row.value >= 0
                ? `M${xa.toFixed(1)},${by}H${(xb - r).toFixed(1)}A${r},${r} 0 0 1 ${xb.toFixed(1)},${by + r}V${by + BAR - r}A${r},${r} 0 0 1 ${(xb - r).toFixed(1)},${by + BAR}H${xa.toFixed(1)}Z`
                : `M${xb.toFixed(1)},${by}H${(xa + r).toFixed(1)}A${r},${r} 0 0 0 ${xa.toFixed(1)},${by + r}V${by + BAR - r}A${r},${r} 0 0 0 ${(xa + r).toFixed(1)},${by + BAR}H${xb.toFixed(1)}Z`;
            rowsSvg.push(`<path d="${d}" fill="${fill}"><title>${esc(`${row.label}: ${fmt(row.value)} (${shortLabel(row)})`)}</title></path>`);
            let reach = row.value >= 0 ? xb : xa;
            if (Array.isArray(row.ci)) {
                const [lo, hi] = row.ci;
                const cy = by + BAR / 2;
                rowsSvg.push(`<path d="M${x(lo).toFixed(1)},${cy}H${x(hi).toFixed(1)}M${x(lo).toFixed(1)},${cy - 4}V${cy + 4}M${x(hi).toFixed(1)},${cy - 4}V${cy + 4}" stroke="${c.ci}" stroke-width="1.5" fill="none"/>`);
                reach = row.value >= 0 ? Math.max(reach, x(hi)) : Math.min(reach, x(lo));
            }
            const label = fmt(row.value);
            if (row.value >= 0) text(reach + 6, by + BAR - 1, label, { size: SIZE.value, weight: 600 });
            else text(reach - 6, by + BAR - 1, label, { size: SIZE.value, weight: 600, anchor: 'end' });
            y = top + ROW;
        }
    }
    const plotBottom = y;

    // Grid and the zero line sit UNDER the bars, so they are drawn first, and
    // stop where a label crosses them: with a transparent background there is
    // no page colour to paint behind the text, and a line through a word reads
    // as a strike. A line on the image's edge would run along the right-aligned
    // source names, so the edges get a tick label and no line.
    const vertical = (lx) => {
        const cuts = boxes.filter((b) => lx >= b.x1 && lx <= b.x2 && b.y2 > plotTop && b.y1 < plotBottom)
            .sort((a, b) => a.y1 - b.y1);
        const segs = [];
        let from = plotTop;
        for (const b of cuts) {
            if (b.y1 > from) segs.push([from, b.y1]);
            from = Math.max(from, b.y2);
        }
        if (from < plotBottom) segs.push([from, plotBottom]);
        return segs.map(([a, b]) => `M${lx.toFixed(1)},${a.toFixed(1)}V${b.toFixed(1)}`).join('');
    };
    const grid = [];
    const inner = ticks.filter((t) => t !== 0 && x(t) > 2 && x(t) < W - 2).map((t) => vertical(x(t))).join('');
    if (inner) grid.push(`<path d="${inner}" stroke="${c.grid}" stroke-width="1" fill="none"/>`);
    grid.push(`<path d="${vertical(x0)}" stroke="${c.zero}" stroke-width="1.5" fill="none"/>`);

    y = plotBottom + SIZE.axis + 6;
    for (const t of ticks) {
        const anchor = x(t) < 12 ? 'start' : x(t) > W - 12 ? 'end' : 'middle';
        text(x(t), y, t === 0 ? '0' : fmt(t).replace(/0$/, ''), { size: SIZE.axis, fill: c.quiet, anchor });
    }
    y += SIZE.small + 8;
    text(x0, y, data.axis.label, { size: SIZE.small, fill: c.quiet, anchor: 'middle' });
    y += 12;
    for (const line of data.note) { y += SIZE.small + 5; text(0, y, line, { size: SIZE.small, fill: c.quiet }); }
    const H = Math.ceil(y + 6);

    // The labels and values were pushed into `parts` in reading order; the grid
    // and bars go underneath them.
    const titleText = data.title.join(' ');
    const svg = [
        `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t d" font-family="${FONT}">`,
        `<title id="t">${esc(titleText)}</title>`,
        `<desc id="d">${esc(data.groups.flatMap((g) => g.rows.map((r) => `${r.label}, ${shortLabel(r)}: ${fmt(r.value)}`)).join('; '))}</desc>`,
        ...grid,
        ...rowsSvg,
        ...parts,
        '</svg>',
        '',
    ].join('\n');
    return { svg, texts };
}

export const renderSvg = (data, theme) => layout(data, theme).svg;

/**
 * A table cell: a `|` would split the cell and a `[` or `]` would break the
 * source link. A `\` is doubled too, so it shows as typed and cannot cancel the
 * escape in front of a `|` that follows it.
 */
const cell = (s) => String(s).replace(/([\\|[\]])/g, '\\$1');

/** The table of sources in the doc: one row per bar, in the chart's order. */
export function renderTable(data) {
    const lines = [
        TABLE_START,
        '',
        '| Result | Effect | 95% CI | Studies or people | Compared with | Note | Source |',
        '| --- | --- | --- | --- | --- | --- | --- |',
    ];
    for (const group of data.groups) {
        lines.push(`| **${cell(group.label)}** | | | | | | |`);
        for (const r of group.rows) {
            const ci = Array.isArray(r.ci) ? `${fmt(r.ci[0])} to ${fmt(r.ci[1])}` : 'not extracted';
            const effect = r.metric === 'SD' ? `${fmt(r.value)} SD` : `${r.metric} = ${fmt(r.value)}`;
            const link = `[${cell(r.source.cite)}](${r.source.url})`;
            lines.push(`| ${[r.label, effect, ci, r.size, r.compared, r.note || '', link].map((v, i) => (i === 6 ? v : cell(v))).join(' | ')} |`);
        }
    }
    lines.push('', TABLE_END);
    return lines.join('\n');
}

export const loadData = () => JSON.parse(readFileSync(DATA_PATH, 'utf8'));

/** Compare as LF: a Windows checkout with autocrlf holds these files as CRLF. */
export const lf = (s) => s.replace(/\r\n/g, '\n');

/**
 * The doc with its table replaced by a fresh one, as LF. Throws unless each
 * marker is there exactly once, start before end: a second copy of the table
 * would otherwise stay in the doc, stale, while the first one passes.
 */
export function docWithTable(doc, data) {
    const text = lf(doc);
    const count = (m) => text.split(m).length - 1;
    const a = text.indexOf(TABLE_START);
    const b = text.indexOf(TABLE_END);
    if (count(TABLE_START) !== 1 || count(TABLE_END) !== 1 || b < a) {
        throw new Error(`${DOC_PATH} needs each evidence-table marker exactly once, start before end`);
    }
    return text.slice(0, a) + renderTable(data) + text.slice(b + TABLE_END.length);
}

/** Every generated file and what it should hold, as LF. */
export function expectedOutputs(data = loadData()) {
    return [
        ...Object.keys(THEMES).map((t) => [svgPath(t), renderSvg(data, t)]),
        [DOC_PATH, docWithTable(readFileSync(DOC_PATH, 'utf8'), data)],
    ];
}

function main() {
    const check = process.argv.includes('--check');
    let stale = 0;
    for (const [path, content] of expectedOutputs()) {
        let current = null;
        try { current = readFileSync(path, 'utf8'); } catch { /* missing = stale */ }
        if (current !== null && lf(current) === content) continue;
        if (check) { stale++; console.log(`stale: ${path}`); continue; }
        // Keep the line endings the checkout already uses for the file.
        const crlf = current !== null && current.includes('\r\n');
        writeFileSync(path, crlf ? content.replace(/\n/g, '\r\n') : content);
        console.log(`wrote ${path}`);
    }
    if (check && stale) { console.log('Run: node tools/evidence-chart.mjs'); process.exit(1); }
    if (check) console.log('evidence chart and table are up to date');
}

// Compare real paths: run through a junction, a symlink or a subst drive, argv[1]
// is the path as typed while import.meta.url is already resolved, and a plain
// comparison would skip main() and let `--check` pass without checking.
const real = (p) => { try { return realpathSync.native(p); } catch { return p; } };
if (process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url))) main();
