#!/usr/bin/env node
/**
 * Write `src/i18n/enPlurals.ts` — the ONLY part of en.json the app ships to an
 * English reader.
 *
 * Why there is an exception at all. The key is the English string, so English
 * needs no resources: i18next finds nothing and hands back the key, which is
 * already the sentence. That is true for every kind of key except one. A
 * count-based key has TWO English strings and the key can only be one of them,
 * so `t('{{count}} cards', { count: 1 })` returned "1 cards" — in the app's own
 * language, for all 32 plural keys (measured 2026-09-15). The codebase had
 * worked around it by appending the 's' in JSX, which put a bare Latin "s" on
 * the end of every translated word: the Russian atlas read "2 287 темаs из
 * проекта «18»s, сгруппировано в 117 регионs".
 *
 * So English loads its plural forms and nothing else — 64 entries, ~6 KB, which
 * is what the whole workaround cost in correctness. Non-plural keys still
 * resolve to themselves and an unknown key still falls back to its own text.
 *
 *   node tools/i18n-en-plurals.mjs           write the file
 *   node tools/i18n-en-plurals.mjs --check   fail if it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const source = join(root, 'src', 'locales', 'en.json');
const target = join(root, 'src', 'i18n', 'enPlurals.ts');

const PLURAL_SUFFIX = /_(zero|one|two|few|many|other)$/;

export function buildEnPlurals(en) {
    const entries = Object.entries(en).filter(([k]) => PLURAL_SUFFIX.test(k));
    entries.sort(([a], [b]) => a.localeCompare(b, 'en'));
    const body = entries.map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
    return `// GENERATED by tools/i18n-en-plurals.mjs — do not edit by hand.
//
// The English plural forms, and only those. See the tool for why English needs
// these and nothing else. Regenerate after adding a count-based key:
//
//     node tools/i18n-en-plurals.mjs
//
// \`tools/i18n-gates.mjs\` fails if this file and en.json disagree.

const enPlurals: Record<string, string> = {
${body}
};

export default enPlurals;
`;
}

// Only when RUN. `i18n-plural-gates.mjs` imports `buildEnPlurals` to check the
// generated file against en.json, and a gate that writes the thing it is
// checking proves nothing.
const runDirectly = resolve(process.argv[1] || '') === resolve(fileURLToPath(import.meta.url));

if (!runDirectly) { /* imported for buildEnPlurals only */ } else {
const en = JSON.parse(readFileSync(source, 'utf8'));
const text = buildEnPlurals(en);
const check = process.argv.includes('--check');
const current = (() => { try { return readFileSync(target, 'utf8'); } catch { return null; } })();

if (check) {
    if (current === text) {
        process.stdout.write(`ok  src/i18n/enPlurals.ts matches en.json (${(text.match(/^ {4}"/gm) || []).length} entries)\n`);
    } else {
        process.stdout.write('FAIL  src/i18n/enPlurals.ts is out of date — run: node tools/i18n-en-plurals.mjs\n');
        process.exit(1);
    }
} else {
    writeFileSync(target, text);
    process.stdout.write(`src/i18n/enPlurals.ts: ${(text.match(/^ {4}"/gm) || []).length} entries\n`);
}
}
